"""Catalog every run under runs/ into a chronological, scannable index — NON-destructive.

The runs/ folder is chaotic (fix*/robust*/run*/novelty_val/... — names don't sort or self-describe).
Renaming the dirs would break the many path references in reports/, the probes (default runs/fix2,
runs/fix4), and HANDOFF — so instead this reads each run's own oracle.jsonl and writes a dated table
to runs/INDEX.md, sorted oldest->newest. Every fact is oracle-derived (the project's "oracle, not
narration" rule): when it ran, how many steps, which maps, whether a battle/badge was reached, and
manual-vs-auto split (from play_record.py rows). runs/ is gitignored, so INDEX.md is a regenerable
local view — re-run this whenever it drifts.

    uv run python -m eval.index_runs
"""
from __future__ import annotations

import glob
import json
import os
from collections import Counter
from datetime import datetime

RUNS = "runs"
_BATTLE = {0: "-", 1: "wild", 2: "trainer"}


def summarize(d: str) -> dict:
    op = os.path.join(d, "oracle.jsonl")
    info = {"name": os.path.basename(d), "rows": 0, "maps": set(), "first": None, "last": None,
            "battle": 0, "badges": 0, "modes": Counter(),
            "has_oracle": os.path.exists(op),
            "mp4": len(glob.glob(os.path.join(d, "*.mp4"))),
            "states": len(glob.glob(os.path.join(d, "*.state"))),
            "frames": len(glob.glob(os.path.join(d, "frame_*.png")))}
    if info["has_oracle"]:
        with open(op, encoding="utf-8") as f:
            for line in f:
                try:
                    r = json.loads(line)
                except Exception:
                    continue
                info["rows"] += 1
                if info["first"] is None and r.get("t"):
                    info["first"] = r["t"]
                if r.get("t"):
                    info["last"] = r["t"]
                if r.get("map_id") is not None:
                    info["maps"].add(r["map_id"])
                info["battle"] = max(info["battle"], r.get("in_battle") or 0)
                info["badges"] = max(info["badges"], r.get("badges") or 0)
                if r.get("mode"):
                    info["modes"][r["mode"]] += 1
    if info["first"] is None:                       # no oracle / no timestamps -> fall back to mtime
        info["first"] = os.path.getmtime(d)
    return info


def _dur(info: dict) -> str:
    if not info["last"] or not info["first"] or info["last"] <= info["first"]:
        return "-"
    m = (info["last"] - info["first"]) / 60.0
    return f"{m:.0f}m"


def main() -> int:
    dirs = sorted(d for d in glob.glob(os.path.join(RUNS, "*")) if os.path.isdir(d))
    infos = sorted((summarize(d) for d in dirs), key=lambda i: i["first"] or 0)

    lines = ["# runs/ index", "",
             f"_Generated by `eval/index_runs.py` — {len(infos)} run dirs, oldest first. "
             "Facts are oracle-derived; runs/ is gitignored so this file is a regenerable local view._",
             "",
             "| date | run | steps | maps | maps seen | battle | badges | mode (man/auto) | extras |",
             "|------|-----|------:|-----:|-----------|--------|-------:|-----------------|--------|"]
    for i in infos:
        date = datetime.fromtimestamp(i["first"]).strftime("%Y-%m-%d %H:%M") if i["first"] else "?"
        maps = ",".join(str(m) for m in sorted(i["maps"])) if i["maps"] else "-"
        if len(maps) > 40:
            maps = maps[:37] + "…"
        man, auto = i["modes"].get("manual", 0), i["modes"].get("auto", 0)
        mode = f"{man}/{auto}" if (man or auto) else "-"
        extras = ", ".join(filter(None, [
            f"{i['frames']} frames" if i["frames"] else "",
            f"{i['mp4']} mp4" if i["mp4"] else "",
            f"{i['states']} states" if i["states"] else "",
            "" if i["has_oracle"] else "NO oracle"]))
        steps = i["rows"] if i["has_oracle"] else "-"
        lines.append(f"| {date} | {i['name']} | {steps} | {len(i['maps']) or '-'} | {maps} | "
                     f"{_BATTLE.get(i['battle'], '?')} | {i['badges']} | {mode} | {extras} |")

    out = os.path.join(RUNS, "INDEX.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    print(f"wrote {out}  ({len(infos)} runs)")
    print("\n".join(lines[4:]))           # echo the table to the console
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
